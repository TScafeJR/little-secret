for (const word in synonyms_data) {
  const innerPairs = [word];
  for (const s of synonyms_data[word]) {
    innerPairs.push(s);
  }

  for (let i = 0; i < innerPairs.length; i++) {
    for (let j = 0; j < innerPairs.length; j++) {
      if (i !== j) {
        allPairs.push({ [innerPairs[i]]: innerPairs[j] });
      }
    }
  }
}

